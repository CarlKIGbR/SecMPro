def _fmt(layout):
    return ", ".join(f"`{n}` {k}" for n, k in layout)


def _short(name, value):
    if isinstance(value, str) and len(value) > 24 and name not in ("label", "column", "manipulation"):
        return f"{len(value) // 2} B"
    return json.dumps(value) if not isinstance(value, str) else f"`{value}`"


def _row(case):
    ins = ", ".join(f"`{k}` {_short(k, v)}" for k, v in case["inputs"].items())
    if "outputs" in case:
        last = ", ".join(f"`{k}` {len(v) // 2} B" for k, v in case["outputs"].items())
    else:
        last = f"reject: `{case['manipulation']}` (from {case['from']})"
    what = {"keys": "ten keys from one `mk`", "wrap": "profile wrap", "wrap-reject": "unlock reject",
            "seal": "record seal", "seal-reject": "record open reject", "backup": "backup file",
            "backup-reject": "backup open reject"}[case["op"]]
    return f"| `{case['id']}` | `{case['op']}` | {what} | {ins} | {last} |"


def render() -> str:
    doc = json.loads(vectorfile.canonical_json(vectorfile.suite_document("store", store_cases.store_cases())))
    rej = sum(1 for c in doc["cases"] if c.get("expect") == "reject")
    m, t, p = store.PROFILE
    return HEAD.format(
        total=len(doc["cases"]), n_pos=len(doc["cases"]) - rej, n_rej=rej, m=m, t=t, p=p, wrap_len=store.WRAP_LEN,
        bwrap_len=store.BWRAP_LEN, header_len=store.HEADER_LEN, keys_stream=_fmt(store_cases.KEYS_STREAM),
        wrap_stream=_fmt(store_cases.WRAP_STREAM), backup_stream=_fmt(store_cases.BACKUP_STREAM),
        rows="\n".join(_row(c) for c in doc["cases"]))


def main():
    text = render()
    OUT.write_text(text, encoding="utf-8")
    print(f"{OUT.name}: {len(text.splitlines())} lines")


if __name__ == "__main__":
    main()
